export function Button({ variant = 'ghost', size = 'md', className = '', ...props }) {
  return <button className={`btn btn-${variant} btn-${size} ${className}`} {...props} />;
}

export function Badge({ tone = 'neutral', children }) {
  return <span className={`badge badge-${tone}`}>{children}</span>;
}

export function Field({ label, full, children, hint }) {
  return (
    <label className={`field ${full ? 'field-full' : ''}`}>
      <span className="field-label">{label}</span>
      {children}
      {hint && <span className="field-hint">{hint}</span>}
    </label>
  );
}

export function Drawer({ open, onClose, title, children, side = 'right' }) {
  useEffect(() => {
    if (!open) return;
    const onKey = (e) => e.key === 'Escape' && onClose();
    document.addEventListener('keydown', onKey);
    document.body.style.overflow = 'hidden';
    return () => { document.removeEventListener('keydown', onKey); document.body.style.overflow = ''; };
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className={`overlay overlay-${side}`} onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <aside className={`sheet sheet-${side}`} role="dialog" aria-modal="true" aria-label={title}>
        <header className="sheet-head">
          <h2>{title}</h2>
          <Button variant="icon" onClick={onClose} aria-label="Close"><Icon name="x" /></Button>
        </header>
        <div className="sheet-body">{children}</div>
      </aside>
    </div>
  );
}
